// Builds body_living.gdshader from male_body_muscular_skin.gdshader: the same 8-shade banded lighting, dither and
// drawn details (nails, tendons, veins, creases, armpit shadow, nipples, shorts), with living skin tones and
// variants (freckles, clean shaven, hairy, old) painted on top.
// Usage: node gen_living_shader.js male_body_muscular_skin.gdshader body_living.gdshader
//
// Skin tones come in groups by heritage, one group at a time. Groups and tones are never named for a color of
// person; tones get material and pigment names. Each tone is a block of seven ramps
// (skin, flush, old skin, nails, freckles, age spots, palms and soles). To add a group, append its tones to TONES
// below: existing tone numbers never move.
const fs = require('fs');
const src = fs.readFileSync(process.argv[2], 'utf8');

const { hex, ramp, NAILBASE, nailFor, SHARED, TONES } = require('./skin_tones.js');   // the palettes live there

const RAMPS = [...SHARED];
TONES.forEach(t => { const sk = ramp(t.skin), n = t.name.toUpperCase().replace(/ /g, '_');
  RAMPS.push([`${n}_SKIN`, sk], [`${n}_FLUSH`, ramp(t.flush)], [`${n}_OLD`, ramp(t.old)], [`${n}_NAIL`, nailFor(sk)],
    [`${n}_FRECKLE`, ramp(t.freckle)], [`${n}_SPOT`, ramp(t.spot)], [`${n}_PALM`, ramp(t.palm || t.skin)]); });

const vec = c => `vec3(${c.map(v => (v / 255).toFixed(4)).join(', ')})`;
const consts = SHARED.map(([n], i) => `const int ${n} = ${i};`).join('\n') + `\nconst int TONES = ${SHARED.length}; // skin tone t uses ramps TONES + t*7 + (0 skin, 1 flush, 2 old skin, 3 nails, 4 freckles, 5 age spots, 6 palms)`;
const table = `const vec3 RAMPS[${RAMPS.length * 8}] = vec3[${RAMPS.length * 8}](\n${RAMPS.map(([n, r], i) => '\t' + r.map(vec).join(', ') + (i < RAMPS.length - 1 ? ',' : '') + ' // ' + n).join('\n')}\n);`;
const greyShow = `const float GREY_SHOW[${TONES.length}] = float[${TONES.length}](${TONES.map(t => (t.grey ?? 1).toFixed(2)).join(', ')}); // how much grey body hair shows on each tone`;
const hasPalm = `const bool HAS_PALM[${TONES.length}] = bool[${TONES.length}](${TONES.map(t => t.palm ? 'true' : 'false').join(', ')}); // tones with their own palm and sole color`;
const toneDoc = TONES.map((t, i) => `${i} ${t.name}`).join(', ');

// ---- reuse the drawn-detail code from the approved body shader as-is
const a = src.indexOf('float b2(vec2 a)');
const b = src.indexOf('\tfloat ix=min(');
if (a < 0 || b < 0) throw new Error('male_body_muscular_skin.gdshader layout changed: detail block not found');
const details = src.slice(a, b);
const fi = details.indexOf('void fragment() {');
const helpers = details.slice(0, fi), fragHead = details.slice(fi + 'void fragment() {'.length);

const out = `// MaleBody_Muscular living skin shader for Godot 4. Same 8-shade banded lighting, dither and drawn details as
// male_body_muscular_skin.gdshader (nails, tendons, veins, creases, armpit shadow, nipples, shorts), with skin tones
// and looks painted on top. Generated by source/gen_living_shader.js. Compiled and test-rendered in Godot 4.5.
//
// Per-body values (instance uniforms, set by living_body.gd):
//   skin_tone   ${toneDoc}
//               (European 0-2, African 3-5, Latin American 6-8, Asian 9-11, Middle Eastern & South Asian 12-14)
//   variant     0 freckles, 1 clean shaven, 2 hairy, 3 old, 4 vitiligo
//   hair_color  0 blond, 1 ginger, 2 brown, 3 dark, 4 grey. Colors the body hair, stubble and freckle-variant hair.
//   look_seed   any number; moves the freckles, hair, spots and blotches so no two bodies match.
// Data it reads from the mesh: UV and UV2 (fine coordinates), COLOR (r = shadow amount, g = rest depth,
// a = part code / 15). Part codes: 0 head, neck, forearms, fingers, calves; 1 toes; 2 upper arms and ears;
// 3 torso; 4/5 hands; 6/7 feet; 8 thighs.
shader_type spatial;
render_mode unshaded;

uniform vec3 key_dir = vec3(-0.46, 0.63, 0.63); // light direction, in view space
uniform float ambient = 0.13;
uniform float pixel_size = 1.0; // screen pixels per art pixel, for the dither pattern
uniform float grit = 0.08;      // share of pixels nudged a shade lighter or darker: a little skin texture

instance uniform int skin_tone = 1;
instance uniform int variant : hint_range(0, 4) = 1;
instance uniform int hair_color : hint_range(0, 4) = 2;
instance uniform float look_seed = 0.0;

${consts}
${hasPalm}
${greyShow}
${table}

varying vec3 v_body; // rest position on the body in metres (feet at 0, facing +Z), so freckles and hair stay on the skin as he moves

${helpers}float h13(vec3 p){p=fract(p*0.1031);p+=dot(p,p.zyx+31.32);return fract((p.x+p.y)*p.z);}
float vno(vec3 p){vec3 i=floor(p),f=fract(p);f=f*f*(3.0-2.0*f);return mix(mix(mix(h13(i),h13(i+vec3(1,0,0)),f.x),mix(h13(i+vec3(0,1,0)),h13(i+vec3(1,1,0)),f.x),f.y),mix(mix(h13(i+vec3(0,0,1)),h13(i+vec3(1,0,1)),f.x),mix(h13(i+vec3(0,1,1)),h13(i+vec3(1,1,1)),f.x),f.y),f.z);}
float fbm3(vec3 p){return (vno(p)*0.5+vno(p*2.03+3.1)*0.25+vno(p*4.07+7.7)*0.125)/0.875;}
float rdg(vec3 p){return 1.0-abs(vno(p)*2.0-1.0);}
vec3 pal(int r,float ix){return RAMPS[r*8+int(clamp(ix,0.0,7.0))];}

void vertex() {
	// the model stores each vertex's rest position in CUSTOM0.xyz. VERTEX here is already posed by the skeleton, so
	// painting from it would leave freckles and hair hanging in the air as limbs move. A model without that data
	// (all zero) falls back to the posed position.
	v_body = dot(CUSTOM0.xyz, CUSTOM0.xyz) > 0.000001 ? CUSTOM0.xyz : VERTEX;
}

void fragment() {${fragHead}	// ---------------- living skin
	vec3 bp=v_body;
	vec3 sp=bp+look_seed*vec3(1.31,0.71,2.17);
	float dth=b4(floor(FRAGCOORD.xy/pixel_size));
	float base=floor(clamp((1.1-(I-cf))/1.1,0.0,0.999)*8.0);
	int tb=TONES+skin_tone*7;
	bool aged=variant==3;
	// where on the body this pixel is (see the part codes above)
	bool head=code<0.5&&bp.y>1.55;
	bool face=head&&bp.z>0.015;
	bool neck=code<0.5&&bp.y>1.44&&bp.y<=1.55&&abs(bp.x)<0.1;
	bool fore=code<0.5&&bp.y>0.8&&bp.y<1.22&&abs(bp.x)>0.16;
	bool shin=code<0.5&&bp.y<0.56;
	bool thigh=code>7.5;
	bool uarm=code>1.5&&code<2.5&&bp.y<1.6;
	bool ear=code>1.5&&code<2.5&&bp.y>=1.6;
	bool torso=code>2.5&&code<3.5;
	bool hand=code>3.5&&code<5.5;
	bool foot=(code>5.5&&code<7.5)||(code>0.5&&code<1.5);
	int r=aged?tb+2:tb;
	float ix=base+rim;
	if(nail){
		r=tb+3;
	}else if(cl){
		r=CLOTH;
		ix=base+1.0+rim;
	}else{
		// a little skin texture, and a living flush where the blood sits close: ears, cheeks, nose, knuckles,
		// elbows, knees and the soles of the feet
		float gh=h13(vec3(floor(FRAGCOORD.xy/pixel_size),7.0));
		ix+=gh<grit*0.5?1.0:(gh<grit?-1.0:0.0);
		float cheek=face?exp(-(q2(abs(bp.x)-0.045)/0.0004+q2(bp.y-1.63)/0.0008)):0.0;
		float nose=face?exp(-(q2(bp.x)/0.00015+q2(bp.y-1.66)/0.0006))*smoothstep(0.05,0.075,bp.z):0.0;
		float knee=(shin||thigh)?exp(-q2(bp.y-0.52)/0.0012)*smoothstep(0.0,0.04,bp.z-0.0):0.0;
		float elbow=fore?smoothstep(1.06,1.14,bp.y)*smoothstep(0.0,-0.03,bp.z):0.0;
		float fl=(ear?0.75:0.0)+cheek*0.7+nose*0.6+knee*0.5+elbow*0.45+(hand?0.3:0.0)+(foot?0.35:0.0);
		if(fl*(0.55+0.45*fbm3(sp*9.0))>0.3+dth*0.35)r=tb+1;
		// palms and soles (the palm side of the hand plate, the underside of the foot and toes) have their own,
		// lighter color on the deeper tones; on lighter tones it's the same as the skin
		bool palm=(hand&&w2<0.0)||(code>5.5&&code<7.5&&w2<0.5)||(code>0.5&&code<1.5&&bp.y<0.012);
		if(palm&&HAS_PALM[skin_tone])r=tb+6;

		// body hair: where it grows, how thick for this look, and a pixel-sized strand pattern anchored to the body
		float chest=torso?smoothstep(0.0,0.04,bp.z)*smoothstep(1.19,1.27,bp.y)*(1.0-smoothstep(1.40,1.46,bp.y))*(1.0-smoothstep(0.09,0.16,abs(bp.x))):0.0;
		float trail=torso?smoothstep(0.02,0.06,bp.z)*smoothstep(0.96,1.04,bp.y)*(1.0-smoothstep(1.2,1.27,bp.y))*(1.0-smoothstep(0.012,0.035,abs(bp.x))):0.0;
		float upback=torso?smoothstep(0.0,-0.05,bp.z)*smoothstep(1.3,1.42,bp.y)*0.35:0.0;
		float limb=(fore?0.9:0.0)+(shin?0.85:0.0)+(thigh?0.6:0.0)+(uarm?0.22:0.0)+(hand?0.35:0.0)+(foot?0.15:0.0);
		float bodyHair=max(max(chest,trail),max(upback,limb));
		// stubble and beard: jaw, chin, cheeks down to the neck
		float beard=head?(1.0-smoothstep(1.62,1.665,bp.y))*smoothstep(-0.035,0.005,bp.z):0.0;
		beard=max(beard,neck?smoothstep(0.015,0.045,bp.z)*smoothstep(1.49,1.53,bp.y)*0.7:0.0);
		float bodyAmt=variant==2?1.0:(variant==3?0.45:(variant==0||variant==4?0.28:0.05));
		float beardAmt=variant==2?1.0:(variant==3?0.55:(variant==0||variant==4?0.3:0.12));
		float patchy=0.55+0.45*fbm3(sp*7.0+2.0);
		float hd=bodyHair*bodyAmt*patchy*(hair_color==4?GREY_SHOW[skin_tone]:1.0);   // grey hair on dark skin is sparse speckle
		float bd=beard*beardAmt*(0.7+0.3*fbm3(sp*12.0));
		float strand=h13(floor(sp*vec3(320.0,130.0,320.0))+look_seed);   // short strands running down the body
		float stub=h13(floor(sp*420.0)+look_seed+5.0);
		int hair=HAIR_BLOND+hair_color;

		// freckles: dense on the face, shoulders, upper back and arms, in sun-catching clusters
		if(variant==0){
			float top=torso?smoothstep(1.3,1.45,bp.y)*(0.7+0.3*smoothstep(0.0,-0.04,bp.z)):0.0;
			float fz=(face?1.0:0.0)+(head&&!face?0.35:0.0)+top+(uarm?0.85:0.0)+(fore?0.6:0.0)+(hand?0.45:0.0)+(torso?0.15:0.0)+(neck?0.4:0.0)+(ear?0.3:0.0)+0.06;
			fz*=0.45+0.55*fbm3(sp*5.0+9.0);
			vec3 fc=floor(sp*125.0);
			float fh=h13(fc+look_seed*0.37);
			if(fh<fz*0.29){r=tb+4;ix=base+(fh<fz*0.08?1.0:0.0)+rim;}
		}
		// vitiligo: pale patches where the skin has lost its color. Sharp-edged, mostly mirrored left and right, and
		// most often on the hands and fingers, wrists, around the mouth, elbows, knees and feet, with a few elsewhere.
		if(variant==4){
			bool finger=code<0.5&&bp.y<=0.8&&abs(bp.x)>0.16;
			float mouth=face?exp(-(q2(bp.x)/0.0016+q2(bp.y-1.6)/0.0012)):0.0;
			float wrist=fore?smoothstep(0.93,0.86,bp.y):0.0;
			float vz=(hand?1.0:0.0)+(finger?1.0:0.0)+wrist*0.9+mouth*0.9+(face?0.3:0.0)+elbow*0.8+knee*0.8+(foot?0.75:0.0)
				+(neck?0.35:0.0)+(torso?0.22:0.0)+(uarm?0.2:0.0)+((thigh||shin)?0.2:0.0)+((head&&!face)?0.25:0.0)+(ear?0.3:0.0);
			vec3 vp=vec3(abs(bp.x),bp.y,bp.z)+look_seed*vec3(0.61,0.37,0.83);   // mirrored, so patches tend to match
			float vn=fbm3(vp*4.5)+0.1*vno(vp*30.0);   // big soft shapes with a ragged edge
			float th=0.78-0.3*clamp(vz,0.0,1.0);
			if(vn>th){r=VITILIGO;ix=base+rim;}
			else if(vn>th-0.025&&h13(floor(bp*200.0))>0.4)ix+=1.0;   // a slightly darker rim at the edge
		}
		// old: sallow thinner skin (the old ramp), wrinkles, age spots, and grey hair
		if(aged){
			float wz=(neck?1.0:0.0)+(face?0.35:0.0)+(face&&bp.y>1.69?0.25:0.0)+(fore||hand?0.55:0.0)+(torso&&bp.z>0.0&&bp.y<1.2?0.35:0.0)+(ear?0.4:0.0)+0.2;
			float wr=pow(rdg(sp*vec3(16.0,70.0,16.0)),10.0)+0.5*pow(rdg(sp*vec3(40.0,40.0,40.0)+3.0),14.0);
			if(wr*wz>0.26)ix+=1.0;
			if(neck&&wr*wz>0.5)ix+=1.0;   // deepest on the neck
			float sz=(head?1.0:0.0)+(hand?1.0:0.0)+(fore?0.8:0.0)+(torso&&bp.y>1.35?0.55:0.0)+(uarm?0.45:0.0)+0.12;
			vec3 sc=sp*38.0;
			vec3 sj=fract(sc)-0.5-(vec3(h13(floor(sc)+1.0),h13(floor(sc)+2.0),h13(floor(sc)+3.0))-0.5)*0.4;
			if(h13(floor(sc)+look_seed)<sz*0.3&&length(sj)<0.26+0.18*h13(floor(sc)+4.0)){r=tb+5;ix=base+rim;}
		}
		// hair on top of all that: the strands themselves, and a faint darkening of the skin they grow from
		// From a distance body hair reads as a darker, broken-up shade of the skin with the odd strand catching the
		// eye, so most hair pixels just darken the skin and only a few take the hair color. Fair hair shows less.
		float show=hair_color>=2?1.0:(hair_color==1?0.7:0.45);
		if(r!=tb+5&&r!=tb+4||variant==0){
			if(stub<bd*0.28){r=hair;ix=base;}
			else if(stub<bd*0.8*show)ix+=1.0;
			else if(strand<hd*(variant==2?0.2:0.12)){r=hair;ix=base;}
			else if(strand<hd*(variant==2?0.75:0.5)*show)ix+=1.0;
		}
	}
	vec3 c=pal(r,ix);
	ALBEDO=pow(c,vec3(2.2));
}
`;
fs.writeFileSync(process.argv[3], out);
console.log('wrote', process.argv[3], out.length, 'chars,', RAMPS.length, 'ramps,', TONES.length, 'tones');
